        <script>
            document.addEventListener('DOMContentLoaded', function() {

                const MAX_CHARS = 155;

                document.querySelectorAll('.testimonial-item').forEach(item => {

                    const textWrapper = item.querySelector('.testimonial-text');
                    const textEl = item.querySelector('.text-content');
                    const toggle = item.querySelector('.read-toggle');

                    if (!textEl || !toggle || !textWrapper) return;

                    const fullText = textEl.getAttribute('data-full').trim();

                    if (fullText.length <= MAX_CHARS) return;

                    const shortText = fullText.substring(0, MAX_CHARS) + '...';

                    let expanded = false;

                    // Initial state
                    textEl.textContent = shortText;
                    toggle.textContent = ' Read more';
                    toggle.classList.remove('d-none');

                    toggle.addEventListener('click', function() {

                        if (!expanded) {
                            // READ MORE
                            textEl.textContent = fullText;
                            textWrapper.classList.add('scrollable');
                            toggle.textContent = ' Read less';
                            expanded = true;
                        } else {
                            // READ LESS
                            textEl.textContent = shortText;
                            textWrapper.classList.remove('scrollable');
                            toggle.textContent = ' Read more';
                            expanded = false;
                        }

                    });

                });

            });
        </script>